  function norm(s) {
    return (s || '')
      .replace(/[\u064B-\u065F\u0670\u0640]/g, '')
      .replace(/[أإآٱ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')
      .replace(/[^\u0621-\u064A0-9\s]/g, ' ')
      .replace(/\s+/g, ' ').trim();
  }
  /* نفس التطبيع للكلمات المفتاحية (ى وي متساويين) */
  const N = MOODS.map(m => ({ ...m, nw: m.words.map(norm) }));
  const NC = CRISIS.map(norm);

  function detect(text) {
    const t = ' ' + norm(text) + ' ';
    const scored = N.map(m => ({
      mood: m,
      score: m.nw.reduce((s, w) => s + (w && t.includes(' ' + w + ' ') ? 2 : (w && t.includes(w) ? 1 : 0)), 0)
    })).filter(x => x.score > 0).sort((a, b) => b.score - a.score);
    return scored.slice(0, 2).map(x => x.mood);
  }
  function isCrisis(text) {
    const t = norm(text);
    return NC.some(w => w && t.includes(w));
  }

  function load() {
    try {
      const raw = localStorage.getItem(KEY);
      if (!raw) return { state: 'empty' };
      const v = JSON.parse(raw);
      if (!v || !v.text || !v.ts) { localStorage.removeItem(KEY); return { state: 'empty' }; }
      if (Date.now() - v.ts >= TTL) { localStorage.removeItem(KEY); return { state: 'expired' }; }
      return { state: 'active', text: v.text, ts: v.ts };
    } catch (e) { return { state: 'empty' }; }
  }
  function save(text) {
    try { localStorage.setItem(KEY, JSON.stringify({ text, ts: Date.now() })); return true; }
    catch (e) { return false; }
  }
  function clear() { try { localStorage.removeItem(KEY); } catch (e) {} }

  function remaining(ts) {
    const ms = Math.max(0, TTL - (Date.now() - ts));
    const h = Math.floor(ms / 3600000), m = Math.floor((ms % 3600000) / 60000);
    return h > 0 ? `${h} ساعة و ${m} دقيقة` : `${m} دقيقة`;
  }

  return { MOODS: N, GENERAL, detect, isCrisis, load, save, clear, remaining };
